CREATE OR REPLACE FUNCTION public.velo_apply_retention()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_help int := 0;
  v_mod  int := 0;
  v_days int;
