CREATE OR REPLACE FUNCTION public.accept_help_post(p_post_id text, p_req_id text, p_guardian_name text, p_guardian_av text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_uid    text := auth.uid()::text;
  v_seeker text;
  v_dm_id  uuid;
